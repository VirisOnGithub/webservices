DROP TABLE IF EXISTS react;
DROP TABLE IF EXISTS belong;
DROP TABLE IF EXISTS MESSAGE;
DROP TABLE IF EXISTS CHANNEL;
DROP TABLE IF EXISTS USERS;
DROP TABLE IF EXISTS ATTACHMENT;

CREATE TABLE ATTACHMENT
(
    ida  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255),
    mime VARCHAR(100),
    url  VARCHAR(255)
);

CREATE TABLE USERS
(
    idu              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pseudo           VARCHAR(50)         NOT NULL,
    email            VARCHAR(255) UNIQUE NOT NULL,
    password         VARCHAR(255)        NOT NULL,
    avatar           TEXT,
    inscription_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE CHANNEL
(
    idc           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(100) NOT NULL,
    description   TEXT,
    is_public     BOOLEAN   DEFAULT TRUE,
    url           VARCHAR(255),
    creation_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    idu           INTEGER  NOT NULL, -- Créateur/Admin du canal
    FOREIGN KEY (idu) REFERENCES USERS (idu)
);

CREATE TABLE MESSAGE
(
    idm       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content   TEXT        NOT NULL,
    send_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    edited    BOOLEAN   DEFAULT FALSE,
    edit_date TIMESTAMP,
    idu       INTEGER NOT NULL, -- Auteur
    idc       INTEGER NOT NULL, -- Canal
    ida       INTEGER,          -- Pièce jointe (opt)
    idm_2     INTEGER,          -- Réponse à un message (opt)
    FOREIGN KEY (idm_2) REFERENCES MESSAGE (idm),
    FOREIGN KEY (idc) REFERENCES CHANNEL (idc) ON DELETE CASCADE,
    FOREIGN KEY (ida) REFERENCES ATTACHMENT (ida) ON DELETE SET NULL,
    FOREIGN KEY (idu) REFERENCES USERS (idu)
);

CREATE TABLE belong
(
    PRIMARY KEY (idu, idc),
    idu INTEGER NOT NULL,
    idc INTEGER NOT NULL,
    FOREIGN KEY (idc) REFERENCES CHANNEL (idc) ON DELETE CASCADE,
    FOREIGN KEY (idu) REFERENCES USERS (idu) ON DELETE CASCADE
);

CREATE TABLE react
(
    PRIMARY KEY (idu, idm),
    idu      INTEGER NOT NULL,
    idm      INTEGER NOT NULL,
    reaction VARCHAR(50) NOT NULL, -- Type de réaction (ex: "like", "love", "laugh", etc.)
    FOREIGN KEY (idm) REFERENCES MESSAGE (idm) ON DELETE CASCADE,
    FOREIGN KEY (idu) REFERENCES USERS (idu) ON DELETE CASCADE
);

GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO webuser;